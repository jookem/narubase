// Regenerates public/emoji/ (Twemoji SVGs) and src/lib/emojiManifest.ts from
// every emoji literal actually used in src/**. Run this after adding new
// emoji anywhere in the app (a new phonics word, a new game icon, etc.) so
// the self-hosted set stays in sync — see src/lib/emoji.ts for why we
// self-host instead of relying on the OS's emoji font.
//
//   node scripts/sync-emoji-assets.mjs
import { execSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import twemoji from '@twemoji/api'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const SVG_SRC_DIR = path.join(ROOT, 'node_modules/@twemoji/svg')
const SVG_OUT_DIR = path.join(ROOT, 'public/emoji')
const MANIFEST_OUT = path.join(ROOT, 'src/lib/emojiManifest.ts')

const files = execSync('git ls-files "src/**/*.ts" "src/**/*.tsx"', { cwd: ROOT })
  .toString()
  .split('\n')
  .filter(Boolean)

const EMOJI_RE = /(\p{Extended_Pictographic}(️)?(‍\p{Extended_Pictographic}(️)?)*)/gu

const found = new Set()
for (const f of files) {
  const content = fs.readFileSync(path.join(ROOT, f), 'utf8')
  const matches = content.match(EMOJI_RE)
  if (matches) matches.forEach(m => found.add(m))
}

const mapping = {}
const missing = []
for (const e of found) {
  let cp = twemoji.convert.toCodePoint(e)
  if (!fs.existsSync(path.join(SVG_SRC_DIR, cp + '.svg')) && cp.endsWith('-fe0f')) {
    const stripped = cp.slice(0, -'-fe0f'.length)
    if (fs.existsSync(path.join(SVG_SRC_DIR, stripped + '.svg'))) cp = stripped
  }
  if (fs.existsSync(path.join(SVG_SRC_DIR, cp + '.svg'))) mapping[e] = cp
  else missing.push([e, cp])
}

if (missing.length) {
  console.warn(`WARNING: ${missing.length} emoji have no Twemoji SVG and will fall back to the OS font:`)
  missing.forEach(([e, cp]) => console.warn(`  ${e}  (${cp})`))
}

fs.mkdirSync(SVG_OUT_DIR, { recursive: true })
// Prune anything no longer referenced, then copy the current set.
for (const f of fs.readdirSync(SVG_OUT_DIR)) fs.rmSync(path.join(SVG_OUT_DIR, f))
const codepoints = [...new Set(Object.values(mapping))].sort()
for (const cp of codepoints) {
  fs.copyFileSync(path.join(SVG_SRC_DIR, cp + '.svg'), path.join(SVG_OUT_DIR, cp + '.svg'))
}

const banner = `// AUTO-GENERATED by scripts/sync-emoji-assets.mjs — do not hand-edit.
// The set of Twemoji codepoints self-hosted under public/emoji/, used by
// src/lib/emoji.ts to resolve an emoji character to its image URL.
`
fs.writeFileSync(
  MANIFEST_OUT,
  banner + `export const EMOJI_CODEPOINTS: readonly string[] = ${JSON.stringify(codepoints)}\n`,
)

console.log(`Wrote ${codepoints.length} SVGs to public/emoji/ and ${MANIFEST_OUT}`)
